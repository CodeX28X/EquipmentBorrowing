
using System.Data;
using EquipmentBorrowing.Application;
using EquipmentBorrowing.Domain.Entities;
using EquipmentBorrowing.Domain.Enums;
using EquipmentBorrowing.Infrastructure.Persistence;
using Microsoft.EntityFrameworkCore;

namespace EquipmentBorrowing.Infrastructure.Services;

public sealed class PostgreSqlAtomicBorrowingService
    : IAtomicBorrowingService
{
    private const int MaximumActiveBorrowings = 3;

    private readonly IDbContextFactory<EquipmentBorrowingDbContext>
        _contextFactory;

    public PostgreSqlAtomicBorrowingService(
        IDbContextFactory<EquipmentBorrowingDbContext> contextFactory)
    {
        _contextFactory = contextFactory
            ?? throw new ArgumentNullException(nameof(contextFactory));
    }

    // Represents work prepared within a transaction.
    // Nothing is saved until all validations succeed.
    private sealed record PreparedOperation(
        BorrowingOperationResult? Rejection,
        IReadOnlyList<Borrowing> Borrowings,
        string SuccessMessage)
    {
        public static PreparedOperation Reject(
            string message,
            OperationErrorKind errorKind =
                OperationErrorKind.Validation) =>
            new(
                BorrowingOperationResult.Rejected(
                    message,
                    errorKind),
                Array.Empty<Borrowing>(),
                string.Empty);

        public static PreparedOperation Ready(
            string message,
            IReadOnlyList<Borrowing> borrowings) =>
            new(null, borrowings, message);
    }

    // Centralized transaction execution and error classification.
    private async Task<BorrowingOperationResult> ExecuteAsync(
        Func<EquipmentBorrowingDbContext,
             CancellationToken,
             Task<PreparedOperation>> prepare,
        CancellationToken cancellationToken)
    {
        bool commitAttempted = false;

        try
        {
            // Context creation and transaction creation are now
            // protected by the exception-handling boundary.
            await using var db =
                await _contextFactory.CreateDbContextAsync(
                    cancellationToken);

            await using var transaction =
                await db.Database.BeginTransactionAsync(
                    IsolationLevel.ReadCommitted,
                    cancellationToken);

            // Validate and prepare all changes under row locks.
            PreparedOperation operation =
                await prepare(db, cancellationToken);

            if (operation.Rejection is not null)
            {
                // No changes have been saved.
                // Disposing the transaction rolls it back.
                return operation.Rejection;
            }

            await db.SaveChangesAsync(cancellationToken);

            // Borrowing IDs are now generated by PostgreSQL.
            int[] borrowingIds = operation.Borrowings
                .Select(b => b.BorrowingId)
                .ToArray();

            // From this point onward, a lost acknowledgement
            // may make the commit outcome impossible to confirm.
            commitAttempted = true;

            await transaction.CommitAsync(cancellationToken);

            return BorrowingOperationResult.Success(
                operation.SuccessMessage,
                borrowingIds);
        }
        catch (Exception) when (commitAttempted)
        {
            // Never automatically retry this operation.
            return BorrowingOperationResult.Unknown();
        }
        catch (OperationCanceledException)
            when (cancellationToken.IsCancellationRequested)
        {
            // No commit was attempted.
            return BorrowingOperationResult.Failed(
                "The operation was cancelled before commit. " +
                "No changes were committed.");
        }
        catch (Exception)
        {
            // A failure before the commit attempt cannot have
            // committed this explicit transaction.
            return BorrowingOperationResult.Failed(
                "The database operation failed before commit. " +
                "No changes were committed. " +
                "Check the connection and retry after refreshing.");
        }
    }

    public Task<BorrowingOperationResult> CheckoutAsync(
        int studentId,
        IReadOnlyCollection<int> equipmentIds,
        DateOnly checkoutDate,
        DateOnly expectedReturnDate,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(equipmentIds);

        if (studentId <= 0)
        {
            return Task.FromResult(
                BorrowingOperationResult.Rejected(
                    "Select a valid student."));
        }

        if (equipmentIds.Count == 0)
        {
            return Task.FromResult(
                BorrowingOperationResult.Rejected(
                    "Select at least one equipment item."));
        }

        if (equipmentIds.Any(id => id <= 0))
        {
            return Task.FromResult(
                BorrowingOperationResult.Rejected(
                    "Equipment IDs must be positive."));
        }

        if (equipmentIds.Count != equipmentIds.Distinct().Count())
        {
            return Task.FromResult(
                BorrowingOperationResult.Rejected(
                    "Duplicate equipment selections are not allowed."));
        }

        if (equipmentIds.Count > MaximumActiveBorrowings)
        {
            return Task.FromResult(
                BorrowingOperationResult.Rejected(
                    "A student may borrow at most three active items.",
                    OperationErrorKind.Conflict));
        }

        if (expectedReturnDate <= checkoutDate)
        {
            return Task.FromResult(
                BorrowingOperationResult.Rejected(
                    "Expected return date must be later " +
                    "than checkout date."));
        }

        // Take a snapshot of the requested equipment IDs.
        // Do not depend on a mutable UI collection while running.
        int[] orderedIds = equipmentIds
            .OrderBy(id => id)
            .ToArray();

        return ExecuteAsync(
            async (db, ct) =>
            {
                // Lock student before checking eligibility
                // or active borrowing count.
                var students = await db.Students
                    .FromSqlInterpolated(
                        $"""
                        SELECT * FROM "Students"
                        WHERE "StudentId" = {studentId}
                        FOR UPDATE
                        """)
                    .AsTracking()
                    .ToListAsync(ct);

                Student? student = students.SingleOrDefault();

                if (student is null)
                {
                    return PreparedOperation.Reject(
                        "Student does not exist.",
                        OperationErrorKind.NotFound);
                }

                if (!student.IsAllowedToBorrow)
                {
                    return PreparedOperation.Reject(
                        "Student is not eligible to borrow.",
                        OperationErrorKind.Conflict);
                }

                int activeCount = await db.Borrowings
                    .CountAsync(
                        b => b.StudentId == studentId &&
                             b.Status == BorrowingStatus.Active,
                        ct);

                if (activeCount + orderedIds.Length >
                    MaximumActiveBorrowings)
                {
                    return PreparedOperation.Reject(
                        "Checkout would exceed the " +
                        "three-item borrowing limit.",
                        OperationErrorKind.Conflict);
                }

                var selectedEquipment = new List<Equipment>();

                // Deterministic lock ordering reduces deadlocks.
                foreach (int equipmentId in orderedIds)
                {
                    var items = await db.Equipment
                        .FromSqlInterpolated(
                            $"""
                            SELECT * FROM "Equipment"
                            WHERE "EquipmentId" = {equipmentId}
                            FOR UPDATE
                            """)
                        .AsTracking()
                        .ToListAsync(ct);

                    Equipment? equipment =
                        items.SingleOrDefault();

                    if (equipment is null)
                    {
                        return PreparedOperation.Reject(
                            $"Equipment {equipmentId} does not exist.",
                            OperationErrorKind.NotFound);
                    }

                    if (!equipment.IsAvailable)
                    {
                        return PreparedOperation.Reject(
                            $"Equipment {equipmentId} is unavailable.",
                            OperationErrorKind.Conflict);
                    }

                    bool hasActiveLoan = await db.Borrowings
                        .AnyAsync(
                            b => b.EquipmentId == equipmentId &&
                                 b.Status == BorrowingStatus.Active,
                            ct);

                    if (hasActiveLoan)
                    {
                        return PreparedOperation.Reject(
                            $"Equipment {equipmentId} " +
                            "already has an active borrowing.",
                            OperationErrorKind.Conflict);
                    }

                    selectedEquipment.Add(equipment);
                }

                var borrowings = new List<Borrowing>();

                foreach (Equipment equipment in selectedEquipment)
                {
                    var borrowing = new Borrowing(
                        student,
                        equipment,
                        checkoutDate,
                        expectedReturnDate);

                    equipment.MarkAsBorrowed();

                    db.Borrowings.Add(borrowing);
                    borrowings.Add(borrowing);
                }

                return PreparedOperation.Ready(
                    "Equipment checkout completed.",
                    borrowings);
            },
            cancellationToken);
    }

    public Task<BorrowingOperationResult> ReturnAsync(
        int studentId,
        int equipmentId,
        DateOnly actualReturnDate,
        CancellationToken cancellationToken = default)
    {
        if (studentId <= 0 || equipmentId <= 0)
        {
            return Task.FromResult(
                BorrowingOperationResult.Rejected(
                    "Select a valid student and equipment item."));
        }

        return ExecuteAsync(
            async (db, ct) =>
            {
                // Maintain the same locking order:
                // student first, then equipment.
                var students = await db.Students
                    .FromSqlInterpolated(
                        $"""
                        SELECT * FROM "Students"
                        WHERE "StudentId" = {studentId}
                        FOR UPDATE
                        """)
                    .AsTracking()
                    .ToListAsync(ct);

                if (students.Count == 0)
                {
                    return PreparedOperation.Reject(
                        "Student does not exist.",
                        OperationErrorKind.NotFound);
                }

                // Never reject a return because a student
                // has become ineligible to borrow.
                var items = await db.Equipment
                    .FromSqlInterpolated(
                        $"""
                        SELECT * FROM "Equipment"
                        WHERE "EquipmentId" = {equipmentId}
                        FOR UPDATE
                        """)
                    .AsTracking()
                    .ToListAsync(ct);

                Equipment? equipment =
                    items.SingleOrDefault();

                if (equipment is null)
                {
                    return PreparedOperation.Reject(
                        "Equipment does not exist.",
                        OperationErrorKind.NotFound);
                }

                Borrowing? borrowing = await db.Borrowings
                    .FirstOrDefaultAsync(
                        b => b.StudentId == studentId &&
                             b.EquipmentId == equipmentId &&
                             b.Status == BorrowingStatus.Active,
                        ct);

                if (borrowing is null)
                {
                    return PreparedOperation.Reject(
                        "No active borrowing exists for " +
                        "this student and equipment.",
                        OperationErrorKind.Conflict);
                }

                if (actualReturnDate < borrowing.BorrowedAt)
                {
                    return PreparedOperation.Reject(
                        "Return date cannot precede checkout date.");
                }

                borrowing.MarkAsReturned(actualReturnDate);
                equipment.MarkAsAvailable();

                return PreparedOperation.Ready(
                    "Equipment returned successfully.",
                    new[] { borrowing });
            },
            cancellationToken);
    }

    public Task<BorrowingOperationResult> ReturnByIdAsync(
    int borrowingId,
    DateOnly actualReturnDate,
    CancellationToken cancellationToken = default)
    {
        if (borrowingId <= 0)
        {
            return Task.FromResult(
                BorrowingOperationResult.Rejected(
                    "Borrowing does not exist.",
                    OperationErrorKind.NotFound));
        }

        return ExecuteAsync(
            async (db, ct) =>
            {
                var reference = await db.Borrowings
                    .AsNoTracking()
                    .Where(b => b.BorrowingId == borrowingId)
                    .Select(b => new
                    {
                        b.StudentId,
                        b.EquipmentId
                    })
                    .SingleOrDefaultAsync(ct);

                if (reference is null)
                {
                    return PreparedOperation.Reject(
                        "Borrowing does not exist.",
                        OperationErrorKind.NotFound);
                }

                // Lock the student first.
                var students = await db.Students
                    .FromSqlInterpolated(
                        $"""
                    SELECT * FROM "Students"
                    WHERE "StudentId" = {reference.StudentId}
                    FOR UPDATE
                    """)
                    .AsTracking()
                    .ToListAsync(ct);

                if (students.Count == 0)
                {
                    throw new InvalidOperationException(
                        "Borrowing has no associated student.");
                }

                // Lock the equipment second.
                var items = await db.Equipment
                    .FromSqlInterpolated(
                        $"""
                    SELECT * FROM "Equipment"
                    WHERE "EquipmentId" = {reference.EquipmentId}
                    FOR UPDATE
                    """)
                    .AsTracking()
                    .ToListAsync(ct);

                Equipment? equipment = items.SingleOrDefault();

                if (equipment is null)
                {
                    throw new InvalidOperationException(
                        "Borrowing has no associated equipment.");
                }

                // Revalidate the exact borrowing after locking.
                Borrowing? borrowing = await db.Borrowings
                    .AsTracking()
                    .SingleOrDefaultAsync(
                        b => b.BorrowingId == borrowingId,
                        ct);

                if (borrowing is null)
                {
                    return PreparedOperation.Reject(
                        "Borrowing does not exist.",
                        OperationErrorKind.NotFound);
                }

                if (borrowing.Status != BorrowingStatus.Active)
                {
                    return PreparedOperation.Reject(
                        "This borrowing has already been returned.",
                        OperationErrorKind.Conflict);
                }

                if (actualReturnDate < borrowing.BorrowedAt)
                {
                    return PreparedOperation.Reject(
                        "Return date cannot precede checkout date.",
                        OperationErrorKind.Conflict);
                }

                borrowing.MarkAsReturned(actualReturnDate);
                equipment.MarkAsAvailable();

                return PreparedOperation.Ready(
                    "Equipment returned successfully.",
                    new[] { borrowing });
            },
            cancellationToken);
    }
}
